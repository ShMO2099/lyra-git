package com.jfx.git.core;

import com.jfx.git.model.Profile;

import org.eclipse.jgit.api.Git;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

/**
 * A profile's SSH key: stored with the profile, found for the repository the profile is
 * active on, generated by {@code ssh-keygen}, and handed to ssh on both engines.
 */
class SshKeysTest {

    @TempDir
    Path root;

    private Path workTree;

    @BeforeEach
    void setUp() throws Exception {
        Settings.useFile(root.resolve("settings.properties"));
        workTree = Files.createDirectories(root.resolve("my repo"));
        try (Git git = Git.init().setDirectory(workTree.toFile()).setInitialBranch("main").call()) {
            var config = git.getRepository().getConfig();
            config.setString("user", null, "name", "Test User");
            config.setString("user", null, "email", "test@example.com");
            config.setBoolean("commit", null, "gpgsign", false);
            config.save();
        }
    }

    @AfterEach
    void tearDown() {
        Settings.useFile(null);
        org.eclipse.jgit.lib.RepositoryCache.clear();
    }

    private Path fakeKey(String name) throws Exception {
        Path key = root.resolve(name);
        Files.writeString(key, "not a real key\n");
        Files.writeString(root.resolve(name + ".pub"), "ssh-ed25519 AAAAC3Nza test@example.com\n");
        return key;
    }

    private void activate(Profile profile) {
        ProfileStore.save(profile);
        ProfileStore.setActiveProfileName(ProfileStore.key(workTree.toFile()), profile.name());
    }

    // ------------------------------------------------------------------
    // Stored with the profile
    // ------------------------------------------------------------------

    @Test
    void aProfilesKeyIsStoredAndComesBack() throws Exception {
        Path key = fakeKey("id_work");
        ProfileStore.save(new Profile("Work", "Alice", "alice@work.example", "", false, key.toString()));

        assertEquals(key.toString(), ProfileStore.profile("Work").sshKeyPath());
    }

    /** Profiles saved before there was a key field have five fields, and name no key. */
    @Test
    void aProfileStoredBeforeKeysExistedStillLoads() {
        Settings.put("profiles.list", "Work\tAlice\talice@work.example\tKEY1\ttrue");

        Profile loaded = ProfileStore.profile("Work");

        assertNotNull(loaded, "an older record must not be dropped as corrupt");
        assertEquals("", loaded.sshKeyPath());
        assertEquals("KEY1", loaded.signingKey());
        assertTrue(loaded.gpgSign());
    }

    @Test
    void theOlderConstructorNamesNoKey() {
        assertEquals("", new Profile("Work", "Alice", "a@b", "", false).sshKeyPath());
        assertEquals("", new Profile("Work", "Alice", "a@b", "", false, null).sshKeyPath());
    }

    // ------------------------------------------------------------------
    // Found for a repository
    // ------------------------------------------------------------------

    @Test
    void theKeyOfTheActiveProfileIsTheRepositorysKey() throws Exception {
        Path key = fakeKey("id_work");
        assertNull(SshKeys.keyFor(workTree.toFile()), "no profile is active yet");

        activate(new Profile("Work", "Alice", "alice@work.example", "", false, key.toString()));

        assertEquals(key, SshKeys.keyFor(workTree.toFile()));
        assertNull(SshKeys.keyFor(root.resolve("another repo").toFile()),
                "the profile is active on one repository, not on every one");
        assertNull(SshKeys.keyFor(null));
    }

    @Test
    void aProfileWithoutAKeyOrWithOneThatHasGoneLeavesItToSsh() throws Exception {
        activate(new Profile("Plain", "Alice", "alice@home.example", "", false));
        assertNull(SshKeys.keyFor(workTree.toFile()));

        activate(new Profile("Gone", "Alice", "alice@home.example", "", false,
                root.resolve("deleted_key").toString()));
        assertNull(SshKeys.keyFor(workTree.toFile()),
                "naming a file that is not there would fail every connection outright");
    }

    @Test
    void thePublicKeyIsTheOneLineBesideThePrivateKey() throws Exception {
        Path key = fakeKey("id_work");

        assertEquals("ssh-ed25519 AAAAC3Nza test@example.com", SshKeys.publicKey(key));
        assertNull(SshKeys.publicKey(root.resolve("no_such_key")));
        assertNull(SshKeys.publicKey(null));
    }

    // ------------------------------------------------------------------
    // Generated
    // ------------------------------------------------------------------

    @Test
    void aGeneratedKeyIsARealEd25519PairAndIsNeverWrittenOverAnother() throws Exception {
        assumeTrue(SshKeys.findKeygen() != null, "needs ssh-keygen");
        Path key = root.resolve("new keys").resolve("id_ed25519_work");

        GitResult created = SshKeys.generate(key, "alice@work.example", "");
        assertTrue(created.isOk(), created::getMessage);

        assertTrue(Files.readString(key).startsWith("-----BEGIN OPENSSH PRIVATE KEY-----"));
        String publicKey = SshKeys.publicKey(key);
        assertNotNull(publicKey);
        assertTrue(publicKey.startsWith("ssh-ed25519 "), publicKey);
        assertTrue(publicKey.endsWith("alice@work.example"), "the comment labels the key: " + publicKey);

        String before = Files.readString(key);
        GitResult again = SshKeys.generate(key, "someone else", "");
        assertFalse(again.isOk(), "a private key is not something to replace by accident");
        assertEquals(before, Files.readString(key));
    }

    @Test
    void aGeneratedKeyCanCarryAPassphrase() throws Exception {
        assumeTrue(SshKeys.findKeygen() != null, "needs ssh-keygen");
        Path plain = root.resolve("plain");
        Path locked = root.resolve("locked");

        assertTrue(SshKeys.generate(plain, "c", null).isOk());
        assertTrue(SshKeys.generate(locked, "c", "correct horse").isOk());

        // An encrypted OpenSSH key names its cipher in the header block; an open one says "none".
        String open = new String(java.util.Base64.getMimeDecoder().decode(body(plain)), StandardCharsets.ISO_8859_1);
        String shut = new String(java.util.Base64.getMimeDecoder().decode(body(locked)), StandardCharsets.ISO_8859_1);
        assertTrue(open.contains("none"), "no passphrase, no cipher");
        assertFalse(shut.substring(0, 60).contains("none"), "a passphrase encrypts the key");
        assertNotEquals(SshKeys.publicKey(plain), SshKeys.publicKey(locked));
    }

    private static String body(Path key) throws Exception {
        StringBuilder body = new StringBuilder();
        for (String line : Files.readAllLines(key)) {
            if (!line.startsWith("-----")) body.append(line).append('\n');
        }
        return body.toString();
    }

    // ------------------------------------------------------------------
    // Handed to ssh
    // ------------------------------------------------------------------

    @Test
    void theKeyIsOfferedAloneOnWhateverSshGitWouldHaveRun() {
        Path key = Path.of("C:\\Users\\me\\.ssh\\id work").toAbsolutePath();
        String quoted = "\"" + key.toString().replace('\\', '/') + "\"";

        assertEquals("ssh -i " + quoted + " -o IdentitiesOnly=yes",
                AskpassBridge.identitySshCommand(null, Map.of(), key),
                "forward slashes and quotes: git runs this through a shell");
        assertEquals("ssh -F cfg -i " + quoted + " -o IdentitiesOnly=yes",
                AskpassBridge.identitySshCommand("ssh -F cfg", Map.of(), key),
                "the repository's own core.sshCommand is kept and added to");
        assertEquals("ssh -v -i " + quoted + " -o IdentitiesOnly=yes",
                AskpassBridge.identitySshCommand("ignored", Map.of("GIT_SSH_COMMAND", "ssh -v"), key),
                "GIT_SSH_COMMAND outranks the configuration, as it does for git");
    }

    /** PuTTY's plink does not take OpenSSH's options, so it is left exactly as it was. */
    @Test
    void aProgramThatIsNotOpenSshIsLeftAlone() {
        Path key = root.resolve("id_work");

        assertNull(AskpassBridge.identitySshCommand("plink -batch", Map.of(), key));
        assertNull(AskpassBridge.identitySshCommand(null, Map.of("GIT_SSH", "C:/putty/plink.exe"), key));
        assertNull(AskpassBridge.identitySshCommand(null, Map.of(), null), "no key, nothing to add");
    }

    /**
     * End to end on the CLI engine: a fetch over SSH runs the ssh that was configured,
     * with the profile's key and nothing else on offer. The "ssh" here is a script that
     * writes down what it was started with and fails.
     */
    @Test
    void aFetchOnTheCliEngineOffersTheProfilesKeyAndOnlyThat() throws Exception {
        assumeTrue(NativeGitRunner.isGitInstalled(), "needs a git executable");
        Path key = fakeKey("id_work");
        Path recorded = root.resolve("ssh-args.txt");
        Path fakeSshDir = Files.createDirectories(root.resolve("bin"));
        Path fakeSsh = fakeSshDir.resolve("ssh");
        Files.writeString(fakeSsh, "#!/bin/sh\nprintf '%s\\n' \"$@\" > '"
                + recorded.toString().replace('\\', '/') + "'\nexit 1\n", StandardCharsets.UTF_8);
        fakeSsh.toFile().setExecutable(true);

        try (Git git = Git.open(workTree.toFile())) {
            var config = git.getRepository().getConfig();
            config.setString("core", null, "sshCommand", "'" + fakeSsh.toString().replace('\\', '/') + "'");
            config.save();
            Files.writeString(workTree.resolve("a.txt"), "a\n");
            git.add().addFilepattern("a.txt").call();
            git.commit().setMessage("first").call();
        }
        activate(new Profile("Work", "Alice", "alice@work.example", "", false, key.toString()));

        NativeGitBackend backend = new NativeGitBackend();
        try {
            assertTrue(backend.openRepository(workTree.toFile()));
            assertTrue(backend.addRemote("origin", "ssh://git@example.invalid/team/project.git").isOk());

            GitResult fetched = backend.fetchRemote("origin");
            assertFalse(fetched.isOk(), "the stand-in ssh always fails");

            assumeTrue(Files.exists(recorded), "git on this machine did not run the configured ssh command");
            List<String> args = Files.readAllLines(recorded);
            int identity = args.indexOf("-i");
            assertTrue(identity >= 0, "the key was not offered: " + args);
            assertEquals(key.toAbsolutePath().toString().replace('\\', '/'), args.get(identity + 1),
                    "the path arrives as one argument, spaces and all");
            assertTrue(args.contains("IdentitiesOnly=yes"), "and nothing else may be offered: " + args);
        } finally {
            backend.close();
        }
    }

    // ------------------------------------------------------------------
    // The JGit transport
    // ------------------------------------------------------------------

    @Test
    void eachKeyGetsItsOwnTransportAndNoKeyGetsNone() throws Exception {
        SshSessionManager.install();
        assumeTrue(SshSessionManager.isInstalled(), "the SSH transport could not be installed here");
        Path work = fakeKey("id_work");
        Path home = fakeKey("id_home");

        assertNull(SshSessionManager.factoryForKey(null), "no key: the shared transport is used");
        var forWork = SshSessionManager.factoryForKey(work);
        assertNotNull(forWork);
        assertSame(forWork, SshSessionManager.factoryForKey(work), "one transport per key, kept");
        assertNotEquals(forWork, SshSessionManager.factoryForKey(home),
                "two profiles' keys must not share a transport, or one would offer the other's key");
    }
}
